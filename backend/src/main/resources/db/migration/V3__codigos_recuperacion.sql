-- 7.1.1: códigos de un solo uso para que el cliente recupere su contraseña (RF-65).
-- El código se guarda como hash (BCrypt), nunca en texto plano. Cada solicitud nueva invalida
-- las anteriores de la misma cuenta.
create table codigos_recuperacion (
    id             bigint generated by default as identity primary key,
    usuario_id     bigint       not null references usuarios (id),
    codigo_hash    varchar(100) not null,
    fecha_creacion timestamp(6) with time zone not null,
    expira         timestamp(6) with time zone not null,
    intentos       integer      not null check (intentos >= 0),
    usado          boolean      not null
);

create index ix_codigos_recuperacion_usuario on codigos_recuperacion (usuario_id);
