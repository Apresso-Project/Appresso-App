-- Appresso: esquema inicial (subtarea 8.1.1, modelo de datos basico).
-- Corresponde a las 21 entidades de com.appresso.backend. Documentacion: docs/modelo-de-datos.md
--
-- Reglas para tocar este archivo:
--   * Una vez subido a main NO se edita: cualquier cambio posterior va en un archivo nuevo
--     (V2__descripcion.sql). Flyway guarda una huella de este archivo y se niega a arrancar si cambia.
--   * Debe correr igual en PostgreSQL (produccion) y en H2 en modo PostgreSQL (pruebas): por eso
--     usa solo SQL estandar. Hibernate corre en modo "validate": si una entidad y este archivo
--     no coinciden, el backend no arranca y las pruebas fallan.
--   * Dinero: numeric(14,2). Instantes: timestamp with time zone (se guardan en UTC).
--   * Enumeraciones: varchar con CHECK de sus valores (se guardan por nombre, no por numero).

-- ====================== usuarios ======================

create table usuarios (
    id                bigint generated by default as identity primary key,
    nombre            varchar(100) not null,
    correo            varchar(150) not null unique,
    contrasena_hash   varchar(100) not null,
    rol               varchar(30)  not null
        check (rol in ('ADMINISTRADOR', 'CAJERO', 'MESERO', 'COCINERO', 'CLIENTE')),
    activo            boolean      not null,
    intentos_fallidos integer      not null,
    bloqueado_hasta   timestamp(6) with time zone,
    fecha_creacion    timestamp(6) with time zone not null
);

create table dispositivos_push (
    id             bigint generated by default as identity primary key,
    usuario_id     bigint       not null references usuarios (id),
    token_fcm      varchar(255) not null unique,
    fecha_registro timestamp(6) with time zone not null
);

-- ====================== inventario ======================

create table categorias (
    id     bigint generated by default as identity primary key,
    nombre varchar(80) not null unique,
    activa boolean     not null
);

create table productos (
    id            bigint generated by default as identity primary key,
    categoria_id  bigint         not null references categorias (id),
    nombre        varchar(120)   not null,
    descripcion   varchar(255),
    precio        numeric(14, 2) not null,
    stock_actual  integer        not null,
    umbral_minimo integer        not null,
    activo        boolean        not null
);

-- ====================== fidelizacion (clientes) ======================
-- Va antes de comandas porque una comanda puede asociarse a un cliente.

create table clientes (
    id                       bigint generated by default as identity primary key,
    nombre                   varchar(80) not null,
    apellido                 varchar(80) not null,
    documento                varchar(20) not null unique,
    celular                  varchar(20) not null,
    acepto_tratamiento_datos boolean     not null,
    fecha_aceptacion_datos   timestamp(6) with time zone,
    puntos                   integer     not null check (puntos >= 0),
    fecha_registro           timestamp(6) with time zone not null,
    usuario_id               bigint unique references usuarios (id)
);

-- ====================== comandas ======================

create table mesas (
    id     bigint generated by default as identity primary key,
    nombre varchar(30) not null unique,
    estado varchar(30) not null check (estado in ('DISPONIBLE', 'OCUPADA'))
);

create table comandas (
    id                      bigint generated by default as identity primary key,
    mesa_id                 bigint         not null references mesas (id),
    mesero_id               bigint         not null references usuarios (id),
    cliente_id              bigint references clientes (id),
    estado                  varchar(30)    not null
        check (estado in ('PENDIENTE', 'ENVIADA', 'EN_PREPARACION', 'LISTA', 'CERRADA')),
    subtotal                numeric(14, 2) not null,
    descuento               numeric(14, 2) not null,
    total                   numeric(14, 2) not null,
    identificador_operacion uuid           not null unique,
    fecha_creacion          timestamp(6) with time zone not null,
    fecha_envio             timestamp(6) with time zone
);

create table detalles_comanda (
    id                        bigint generated by default as identity primary key,
    comanda_id                bigint         not null references comandas (id),
    producto_id               bigint         not null references productos (id),
    cantidad                  integer        not null check (cantidad >= 1),
    precio_unitario           numeric(14, 2) not null,
    observaciones             varchar(100),
    agregado_despues_de_envio boolean        not null
);

create table historial_comanda (
    id              bigint generated by default as identity primary key,
    comanda_id      bigint      not null references comandas (id),
    estado_anterior varchar(30)
        check (estado_anterior in ('PENDIENTE', 'ENVIADA', 'EN_PREPARACION', 'LISTA', 'CERRADA')),
    estado_nuevo    varchar(30) not null
        check (estado_nuevo in ('PENDIENTE', 'ENVIADA', 'EN_PREPARACION', 'LISTA', 'CERRADA')),
    descripcion     varchar(255),
    usuario_id      bigint      not null references usuarios (id),
    fecha           timestamp(6) with time zone not null
);

-- Va despues de comandas porque un movimiento de venta apunta a su comanda.
create table movimientos_inventario (
    id               bigint generated by default as identity primary key,
    producto_id      bigint      not null references productos (id),
    tipo             varchar(30) not null
        check (tipo in ('ENTRADA_MANUAL', 'SALIDA_MANUAL', 'VENTA', 'AJUSTE_MERMA')),
    cantidad         integer     not null,
    stock_resultante integer     not null,
    justificacion    varchar(255),
    usuario_id       bigint      not null references usuarios (id),
    comanda_id       bigint references comandas (id),
    fecha            timestamp(6) with time zone not null
);

-- ====================== caja ======================

create table jornadas (
    id                     bigint generated by default as identity primary key,
    estado                 varchar(30)    not null check (estado in ('ABIERTA', 'CERRADA')),
    fecha_apertura         timestamp(6) with time zone not null,
    fecha_cierre           timestamp(6) with time zone,
    saldo_inicial_efectivo numeric(14, 2) not null,
    base_siguiente_jornada numeric(14, 2),
    retiro_excedente       numeric(14, 2),
    abierta_por_id         bigint         not null references usuarios (id),
    cerrada_por_id         bigint references usuarios (id)
);

create table solicitudes_retiro (
    id               bigint generated by default as identity primary key,
    cajero_id        bigint         not null references usuarios (id),
    valor            numeric(14, 2) not null,
    motivo           varchar(255)   not null,
    estado           varchar(30)    not null check (estado in ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    fecha_solicitud  timestamp(6) with time zone not null,
    resuelta_por_id  bigint references usuarios (id),
    fecha_resolucion timestamp(6) with time zone
);

-- Una comanda, un pago: comanda_id es unico. Un pago existe solo si ya fue confirmado.
create table pagos (
    id                      bigint generated by default as identity primary key,
    comanda_id              bigint         not null unique references comandas (id),
    jornada_id              bigint         not null references jornadas (id),
    valor                   numeric(14, 2) not null,
    medio                   varchar(30)    not null check (medio in ('EFECTIVO', 'TRANSFERENCIA')),
    identificador_operacion uuid           not null unique,
    fecha                   timestamp(6) with time zone not null,
    confirmado_por_id       bigint         not null references usuarios (id)
);

create table movimientos_caja (
    id                  bigint generated by default as identity primary key,
    jornada_id          bigint         not null references jornadas (id),
    tipo                varchar(30)    not null check (tipo in ('PAGO', 'INGRESO', 'RETIRO')),
    medio               varchar(30)    not null check (medio in ('EFECTIVO', 'TRANSFERENCIA')),
    valor               numeric(14, 2) not null,
    concepto            varchar(255)   not null,
    fecha               timestamp(6) with time zone not null,
    registrado_por_id   bigint         not null references usuarios (id),
    autorizado_por_id   bigint references usuarios (id),
    pago_id             bigint references pagos (id),
    solicitud_retiro_id bigint references solicitudes_retiro (id)
);

create table informes_cierre (
    id                           bigint generated by default as identity primary key,
    jornada_id                   bigint         not null unique references jornadas (id),
    saldo_inicial_efectivo       numeric(14, 2) not null,
    ingresos_efectivo            numeric(14, 2) not null,
    egresos_efectivo             numeric(14, 2) not null,
    base_reservada               numeric(14, 2) not null,
    saldo_final_efectivo         numeric(14, 2) not null,
    saldo_inicial_transferencias numeric(14, 2) not null,
    ingresos_transferencias      numeric(14, 2) not null,
    egresos_transferencias       numeric(14, 2) not null,
    saldo_final_transferencias   numeric(14, 2) not null,
    fecha_generacion             timestamp(6) with time zone not null
);

-- Una sola fila (datos del local y QR de pago).
create table configuracion_establecimiento (
    id          bigint generated by default as identity primary key,
    nombre      varchar(120) not null,
    qr_pago_url varchar(500)
);

-- ====================== fidelizacion (ofertas) ======================
-- El umbral puntos_minimos de una recompensa es unico solo entre las ACTIVAS (RF-54).
-- No se declara aqui porque H2 no admite indices parciales: lo valida el servicio.

create table recompensas (
    id                 bigint generated by default as identity primary key,
    nombre             varchar(100)   not null,
    descripcion        varchar(255),
    tipo               varchar(30)    not null
        check (tipo in ('DESCUENTO_PORCENTAJE', 'DESCUENTO_VALOR', 'PRODUCTO_GRATIS')),
    valor              numeric(14, 2) not null,
    producto_gratis_id bigint references productos (id),
    puntos_minimos     integer        not null check (puntos_minimos >= 0),
    costo_puntos       integer        not null check (costo_puntos >= 0),
    uso_unico          boolean        not null,
    activa             boolean        not null,
    vigente_desde      date,
    vigente_hasta      date
);

create table promociones (
    id            bigint generated by default as identity primary key,
    titulo        varchar(120) not null,
    descripcion   varchar(500),
    condiciones   varchar(500),
    vigente_desde date         not null,
    vigente_hasta date         not null,
    costo_puntos  integer      not null check (costo_puntos >= 0),
    publicada     boolean      not null,
    activa        boolean      not null
);

-- Cada canje es de una recompensa O de una promocion (lo valida la entidad con @PrePersist).
create table canjes_recompensa (
    id                 bigint generated by default as identity primary key,
    cliente_id         bigint         not null references clientes (id),
    recompensa_id      bigint references recompensas (id),
    promocion_id       bigint references promociones (id),
    comanda_id         bigint         not null references comandas (id),
    usuario_id         bigint         not null references usuarios (id),
    puntos_descontados integer        not null,
    valor_descontado   numeric(14, 2) not null,
    fecha              timestamp(6) with time zone not null
);

create table notificaciones (
    id            bigint generated by default as identity primary key,
    cliente_id    bigint       not null references clientes (id),
    tipo          varchar(30)  not null check (tipo in ('NUEVA_RECOMPENSA', 'PROMOCION')),
    titulo        varchar(120) not null,
    mensaje       varchar(500) not null,
    promocion_id  bigint references promociones (id),
    recompensa_id bigint references recompensas (id),
    leida         boolean      not null,
    fecha         timestamp(6) with time zone not null
);

-- ====================== auditoria ======================

create table registros_auditoria (
    id             bigint generated by default as identity primary key,
    usuario_id     bigint references usuarios (id),
    fecha          timestamp(6) with time zone not null,
    tipo_operacion varchar(60) not null,
    entidad        varchar(60) not null,
    entidad_id     bigint,
    detalle        varchar(2000)
);

-- ====================== indices de consulta ======================
-- PostgreSQL no indexa las llaves foraneas por si solo; se crean las de las consultas frecuentes.

create index idx_comandas_mesa_estado      on comandas (mesa_id, estado);
create index idx_comandas_cliente          on comandas (cliente_id);
create index idx_comandas_estado_fecha     on comandas (estado, fecha_creacion);
create index idx_detalles_comanda          on detalles_comanda (comanda_id);
create index idx_historial_comanda         on historial_comanda (comanda_id, fecha);
create index idx_productos_categoria       on productos (categoria_id);
create index idx_mov_inventario_producto   on movimientos_inventario (producto_id, fecha);
create index idx_pagos_jornada             on pagos (jornada_id);
create index idx_mov_caja_jornada          on movimientos_caja (jornada_id, fecha);
create index idx_jornadas_estado           on jornadas (estado);
create index idx_solicitudes_retiro_estado on solicitudes_retiro (estado);
create index idx_canjes_cliente            on canjes_recompensa (cliente_id);
create index idx_canjes_comanda            on canjes_recompensa (comanda_id);
create index idx_notificaciones_cliente    on notificaciones (cliente_id, leida);
create index idx_auditoria_entidad         on registros_auditoria (entidad, entidad_id);
create index idx_auditoria_fecha           on registros_auditoria (fecha);
